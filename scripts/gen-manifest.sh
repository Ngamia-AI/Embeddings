#!/usr/bin/env bash
# Regenerate models/MANIFEST.sha256 from the GGUF files currently present.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODELS_DIR="${MODELS_DIR:-$ROOT/models}"

shopt -s nullglob
files=("$MODELS_DIR"/*.gguf)
if [ ${#files[@]} -eq 0 ]; then
  echo "no .gguf files in $MODELS_DIR" >&2
  exit 1
fi

{
  echo "# EmbeddingGemma 2 model manifest. Generated by make manifest on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# Regenerate with: make manifest"
  ( cd "$MODELS_DIR" && sha256sum ./*.gguf | sed 's#  \./#  #' )
} > "$MODELS_DIR/MANIFEST.sha256"

cat "$MODELS_DIR/MANIFEST.sha256"
