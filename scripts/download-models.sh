#!/usr/bin/env bash
# Download the pinned EmbeddingGemma 2 GGUF files on the VPS and pin their
# SHA-256 hashes into models/MANIFEST.sha256.
#
# Usage:
#   scripts/download-models.sh            # BF16 text + projector (default)
#   scripts/download-models.sh --q8       # also fetch the Q8_0 pair for Phase 0
#
# Override any *_REPO / *_REV variable to change the pin. Revisions default to
# "main" on purpose: pin the exact commit shown by the Hugging Face UI before a
# production deploy, then commit the resulting MANIFEST.sha256.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MODELS_DIR="${MODELS_DIR:-$ROOT/models}"

TEXT_REPO="${TEXT_REPO:-ggml-org/embeddinggemma-2-GGUF}"
PROJ_REPO="${PROJ_REPO:-AtomicChat/embeddinggemma-2-GGUF}"
TEXT_REV="${TEXT_REV:-main}"
PROJ_REV="${PROJ_REV:-main}"

TEXT_BF16="${TEXT_BF16:-embeddinggemma-2-BF16.gguf}"
TEXT_Q8="${TEXT_Q8:-embeddinggemma-2-Q8_0.gguf}"
PROJ_BF16="${PROJ_BF16:-mmproj-embeddinggemma-2-BF16.gguf}"
PROJ_Q8="${PROJ_Q8:-mmproj-embeddinggemma-2-Q8_0.gguf}"

WANT_Q8=0
for arg in "$@"; do
  case "$arg" in
    --q8) WANT_Q8=1 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

# Resolve the Hugging Face CLI (new `hf` or the legacy `huggingface-cli`).
if command -v hf >/dev/null 2>&1; then
  HF=(hf download)
elif command -v huggingface-cli >/dev/null 2>&1; then
  HF=(huggingface-cli download)
else
  echo "error: install the Hugging Face CLI first: pip install -U huggingface_hub" >&2
  exit 1
fi

mkdir -p "$MODELS_DIR"

fetch() {
  local repo="$1" rev="$2" file="$3"
  if [ -f "$MODELS_DIR/$file" ]; then
    echo "== $file already present, skipping"
    return
  fi
  echo "== downloading $repo/$file @ $rev"
  "${HF[@]}" "$repo" "$file" --revision "$rev" --local-dir "$MODELS_DIR"
}

echo "model directory: $MODELS_DIR"
fetch "$TEXT_REPO" "$TEXT_REV" "$TEXT_BF16"
fetch "$PROJ_REPO" "$PROJ_REV" "$PROJ_BF16"
if [ "$WANT_Q8" -eq 1 ]; then
  fetch "$TEXT_REPO" "$TEXT_REV" "$TEXT_Q8"
  fetch "$PROJ_REPO" "$PROJ_REV" "$PROJ_Q8"
fi

echo "== pinning SHA-256 hashes into $MODELS_DIR/MANIFEST.sha256"
{
  echo "# EmbeddingGemma 2 model manifest. Generated by scripts/download-models.sh"
  echo "# text: $TEXT_REPO@$TEXT_REV"
  echo "# projector: $PROJ_REPO@$PROJ_REV"
  echo "# Regenerate with: make manifest"
  ( cd "$MODELS_DIR" && sha256sum ./*.gguf 2>/dev/null | sed 's#  \./#  #' )
} > "$MODELS_DIR/MANIFEST.sha256"

cat "$MODELS_DIR/MANIFEST.sha256"
echo "done. Start the stack with: make -C '$ROOT' up"
